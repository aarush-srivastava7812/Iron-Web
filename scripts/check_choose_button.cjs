/* Click real recommendation buttons on the home-page chat. Fictional test data only. */
const path=require('node:path');
const {createRequire}=require('node:module');
const {chromium}=createRequire(path.resolve(__dirname,'../dashboard/frontend/package.json'))('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');

(async()=>{
  const origin='http://127.0.0.1:8000', report=path.resolve('report/choose_button_20261022');
  await fs.mkdir(report,{recursive:true});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1050}});
  const page=await context.newPage(), errors=[], requests=[];
  page.setDefaultTimeout(20000);
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(['POST','PUT'].includes(request.method()))requests.push({method:request.method(),url:request.url()});});
  try{
    const login=await context.request.post(origin+'/api/auth/developer',{headers:{Origin:origin,'X-Voyara-Developer':'1'}});
    assert.equal(login.status(),200);
    await page.goto(origin+'/#home');
    await page.locator('.journey-launcher').click();
    await page.locator('.journey-chat-loading').waitFor({state:'hidden'});
    const pending=page.waitForResponse(r=>r.url().endsWith('/assistant/conversations')&&r.request().method()==='POST');
    await page.locator('[data-chat=new]').click();
    const id=(await (await pending).json()).id;
    await page.locator('.journey-chat-loading').waitFor({state:'hidden'});
    await page.locator('#journeyMessage').fill('I want a relaxing solo trip with 50k');
    const advice=page.waitForResponse(r=>r.url().endsWith('/chat')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Send to Voyara AI',exact:true}).click();
    const first=await (await advice).json();
    assert.equal(first.status,'ok',first.reply);
    await page.locator('.journey-chat-loading').waitFor({state:'hidden'});
    const choice=name=>page.locator('.journey-chat-cards .journey-choice').filter({has:page.getByText(name,{exact:true})}).getByRole('button');
    await choice('Munnar').click();
    await page.locator('.journey-chat-loading').waitFor({state:'hidden'});
    const afterFirst=await (await context.request.get(origin+'/api/assistant/conversations/'+id+'/workspace')).json();
    await fs.writeFile(path.join(report,'observed.json'),JSON.stringify({draft:afterFirst.draft,button:await choice('Munnar').innerText(),requests,errors},null,2));
    assert.equal(afterFirst.draft.destination,'Munnar');
    await choice('Munnar').filter({hasText:'Selected'}).waitFor();
    assert.equal(await choice('Munnar').getAttribute('aria-pressed'),'true');
    assert.ok((await page.locator('.journey-chat-messages').innerText()).includes('Munnar it is'));
    await choice('Rishikesh').click();
    await page.locator('.journey-chat-loading').waitFor({state:'hidden'});
    await choice('Rishikesh').filter({hasText:'Selected'}).waitFor();
    assert.equal(await choice('Munnar').innerText(),'Choose');
    await page.locator('#journeyMessage').fill('Mumbai');
    const city=page.waitForResponse(r=>r.url().endsWith('/chat')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Send to Voyara AI',exact:true}).click();
    assert.equal((await (await city).json()).workspace.draft.origin,'Mumbai');
    await page.locator('.journey-chat-loading').waitFor({state:'hidden'});
    const saved=await (await context.request.get(origin+'/api/assistant/conversations/'+id+'/workspace')).json();
    assert.equal(saved.draft.destination,'Rishikesh');
    assert.equal(saved.draft.budget,50000);
    assert.equal(saved.draft.traveller_count,1);
    assert.equal(saved.dialogue.awaiting,'start_date');
    assert.ok((await page.locator('.journey-chat-messages').innerText()).includes('departure date'));
    const count=requests.length;
    await choice('Rishikesh').click();
    assert.equal(requests.length,count);
    await page.screenshot({path:path.join(report,'selected-desktop.png')});
    await page.reload();
    await page.locator('.journey-launcher').click();
    await choice('Rishikesh').filter({hasText:'Selected'}).waitFor();
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.locator('.journey-chat').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
    await page.screenshot({path:path.join(report,'selected-mobile.png')});
    assert.deepEqual(errors,[]);
    const result={passed:true,trip_id:id,selected:saved.draft.destination,revision:saved.revision,requests,errors};
    await fs.writeFile(path.join(report,'acceptance.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result,null,2));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
