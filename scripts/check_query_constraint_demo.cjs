/* Local browser acceptance. All trip values below are fictional test data. */
const {createRequire}=require('node:module');
const {chromium}=createRequire(require('node:path').resolve(__dirname,'../dashboard/frontend/package.json'))('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');

(async()=>{
  const origin=process.env.VOYARA_QUERY_DEMO_URL||'http://127.0.0.1:8000';
  const report=path.resolve('report/query_constraint_agent_20261022');
  await fs.mkdir(report,{recursive:true});
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1050}});
  const page=await context.newPage(), errors=[], checks=[];
  page.setDefaultTimeout(45000);
  page.on('pageerror',error=>errors.push(error.message));
  async function send(message){
    await page.locator('#journeyMessage').fill(message);
    const pending=page.waitForResponse(r=>r.url().endsWith('/chat')&&r.request().method()==='POST');
    await page.getByRole('button',{name:'Send to Voyara AI',exact:true}).click();
    const response=await pending;
    assert.equal(response.status(),200);
    const result=await response.json();
    assert.equal(result.status,'ok',result.reply);
    await page.locator('.journey-chat-loading').waitFor({state:'hidden'});
    return result;
  }
  try{
    const login=await context.request.post(origin+'/api/auth/developer',{headers:{Origin:origin,'X-Voyara-Developer':'1'}});
    assert.equal(login.status(),200,await login.text());
    const csrf=(await context.cookies()).find(cookie=>cookie.name==='voyara_csrf').value;
    const created=await context.request.post(origin+'/api/assistant/conversations',{headers:{Origin:origin,'X-CSRF-Token':csrf},data:{}});
    assert.equal(created.status(),201,await created.text());
    const id=(await created.json()).id;
    await page.goto(origin+'/#travel-book/'+id);
    await page.locator('.journey-book').waitFor();
    await page.locator('.journey-launcher').click();
    await page.locator('.journey-chat[open]').waitFor();
    const first=await send('Kerala, 1 December 2026 for three days, two adults, INR 200000 total; I prefer nature and quiet hotels; ideally a window seat');
    assert.equal(first.workspace.conversation_id,id);
    assert.equal(first.workspace.draft.destination,'Kerala');
    assert.equal(first.workspace.draft.end_date,'2026-12-03');
    assert.equal(first.workspace.draft.budget,200000);
    assert.equal(first.workspace.draft.traveller_count,2);
    assert.equal(first.workspace.draft.hard_requirements.length,0);
    assert.equal(first.workspace.draft.soft_preferences.length,2);
    assert.equal(first.workspace.constraint_analysis.mode,'deterministic');
    await page.locator('.journey-understanding>summary').click();
    await page.getByRole('heading',{name:'Facts & firm constraints',exact:true}).waitFor();
    await page.getByRole('heading',{name:'Preferences',exact:true}).waitFor();
    assert.ok((await page.locator('.journey-constraint-agent').innerText()).includes('quiet hotels'));
    checks.push('Natural-language query updates exact dates, party size and total budget while preserving preferences separately');
    const corrected=await send('Reduce my budget by INR 10000');
    assert.equal(corrected.workspace.draft.budget,190000);
    assert.equal(corrected.workspace.draft.soft_preferences.length,2);
    const before=corrected.workspace.revision;
    const readonly=await send('Show my trip summary');
    assert.equal(readonly.workspace.revision,before);
    checks.push('Budget correction uses deterministic arithmetic; read-only queries preserve the revision');
    await page.locator('.journey-understanding>summary').click();
    await page.locator('.journey-constraint-agent').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(report,'desktop.png')});
    await page.setViewportSize({width:390,height:844});
    await page.locator('.journey-constraint-agent').scrollIntoViewIfNeeded();
    assert.ok(await page.locator('.journey-chat').evaluate(el=>el.scrollWidth<=el.clientWidth+1));
    await page.screenshot({path:path.join(report,'mobile.png')});
    checks.push('Facts and preferences render without horizontal overflow on a 390px screen');
    await page.getByRole('button',{name:'Minimize travel chat',exact:true}).click();
    await page.reload();
    await page.locator('.journey-book').waitFor();
    await page.locator('.journey-launcher').click();
    await page.locator('.journey-understanding>summary').click();
    await page.getByRole('heading',{name:'Preferences',exact:true}).waitFor();
    assert.ok((await page.locator('.journey-constraint-agent').innerText()).includes('quiet hotels'));
    checks.push('Constraint review survives reloading and reopening the trip');
    await page.getByRole('button',{name:'Minimize travel chat',exact:true}).click();
    if(!await page.locator('.journey-manual').evaluate(el=>el.open))await page.locator('.journey-manual>summary').click();
    await page.locator('[name=soft_preferences]').fill('I prefer a pool');
    const saved=page.waitForResponse(r=>r.url().endsWith('/workspace')&&r.request().method()==='PUT');
    await page.getByRole('button',{name:'Save trip details',exact:true}).click();
    const savedResponse=await saved;
    assert.equal(savedResponse.status(),200,await savedResponse.text());
    const finalWorkspace=await savedResponse.json();
    assert.deepEqual(finalWorkspace.draft.soft_preferences,['I prefer a pool']);
    assert.equal(finalWorkspace.draft.hard_requirements.length,0);
    checks.push('Manual preference editing replaces optional wishes without creating mandatory requirements');
    assert.deepEqual(errors,[]);
    await fs.writeFile(path.join(report,'acceptance.json'),JSON.stringify({origin,trip_id:id,checks,errors,workspace:finalWorkspace},null,2));
    console.log(JSON.stringify({passed:true,origin,trip_id:id,checks},null,2));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
